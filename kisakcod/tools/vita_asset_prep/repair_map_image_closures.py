ImageRecord = tuple[int, int, int, int, int, int, int, bytes]

# `$default`/`wc/$default3d` is a renderer-provided white image, not an IWI
# stored in the retail archives.  Carry that exact built-in as a normal VITI
# record so source materials resolve through the ordinary image binding path
# instead of silently creating a runtime fallback texture.  This is a
# renderer default, not generated map artwork.
BUILTIN_IMAGE_RECORDS: dict[str, ImageRecord] = {
    "default": (4, 1, 1, 1, 1, 21, 0, bytes((255, 255, 255, 255))),
}


def _align(value: int) -> int:
    return (value + ALIGNMENT - 1) & ~(ALIGNMENT - 1)


def _base(name: str) -> str:
    return re.sub(r"#\d+$", "", name).lower()


def _map_auxiliary_source(root: Path, folder: str, index: int,
                          map_name: str) -> Path:
    """Resolve a generated per-map effect file under a conversion root."""
    filename = f"{index:02d}-{map_name}.bin"
    # A graph-enriched VFXA sidecar is kept beside the compact v1 fallback
    # while the source FX export is being qualified. Prefer that authored
    # graph for the effect family, but keep the old filename and root-level
    # lookup compatible with existing conversion directories.
    versioned = f"{index:02d}-{map_name}-v2.bin"
    candidates = ((root / folder / versioned, root / versioned,
                   root / folder / filename, root / filename)
                  if folder == "effects"
                  else (root / folder / filename, root / filename))
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise FileNotFoundError(
        f"missing {folder} sidecar for {map_name}: {candidates[0]}")


def _reorder_iwi_mips(payload: bytes, width: int, height: int,
                      levels: int, image_format: int, flags: int = 0) -> bytes:
    """Convert COD4's smallest-first IWI mip stream to base-first order."""
    if not payload or levels <= 1 or width <= 0 or height <= 0:
        return payload
    if image_format in (11, 12, 13):
        block_bytes = 8 if image_format == 11 else 16

        def level_bytes(level_width: int, level_height: int) -> int:
            return ((level_width + 3) // 4) * ((level_height + 3) // 4) * block_bytes
    elif image_format in (1, 2, 3, 4, 5):
        bytes_per_pixel = {1: 4, 2: 3, 3: 2, 4: 1, 5: 1}[image_format]

        def level_bytes(level_width: int, level_height: int) -> int:
            return level_width * level_height * bytes_per_pixel
    else:
        return payload

    sizes = [level_bytes(max(1, width >> level), max(1, height >> level))
             for level in range(levels)]
    face_count = 6 if flags & 0x4 else 1
    if sum(sizes) * face_count != len(payload):
        return payload
    if face_count == 1:
        mip_streams: list[bytes] = []
        offset = 0
        for level in range(levels - 1, -1, -1):
            size = sizes[level]
            mip_streams.append(payload[offset:offset + size])
            offset += size
        return b"".join(reversed(mip_streams))
    face_streams: list[list[bytes]] = [[] for _ in range(face_count)]
    offset = 0
    for level in range(levels - 1, -1, -1):
        size = sizes[level]
        for face in range(face_count):
            face_streams[face].append(payload[offset:offset + size])
            offset += size
    return b"".join(b"".join(reversed(streams)) for streams in face_streams)


class Package:
    def __init__(self, path: Path):
        self.path = path
        with path.open("rb") as stream:
            header = stream.read(HEADER_SIZE)
            if len(header) != HEADER_SIZE:
                raise ValueError("package header is truncated")
            (magic, self.major, self.minor, endian, self.flags,
             header_size, toc_offset, toc_count, self.package_id,
             self.source_hash) = HEADER.unpack(header)
            if magic != MAGIC or endian != 1 or header_size != HEADER_SIZE:
                raise ValueError("unsupported KVAP package header")
            if toc_count == 0 or toc_count > 256:
                raise ValueError("invalid KVAP chunk count")
            stream.seek(toc_offset)
            self.chunks: list[dict[str, Any]] = []
            for index in range(toc_count):
                data = stream.read(TOC_SIZE)
                if len(data) != TOC_SIZE:
                    raise ValueError(f"TOC record {index} is truncated")
                (kind, chunk_flags, asset_id, offset, stored_size, raw_size,
                 alignment, codec, crc32, reserved) = TOC.unpack(data)
                if alignment == 0 or offset + stored_size > path.stat().st_size:
                    raise ValueError(f"TOC record {index} is out of bounds")
                self.chunks.append({
                    "index": index,
                    "type": kind,
                    "chunkFlags": chunk_flags,
                    "assetId": asset_id,
                    "offset": offset,
                    "storedSize": stored_size,
                    "rawSize": raw_size,
                    "alignment": alignment,
                    "codec": codec,
                    "crc32": crc32,
                    "reserved": reserved,
                })

    def read_stored(self, chunk: dict[str, Any]) -> bytes:
        with self.path.open("rb") as stream:
            stream.seek(chunk["offset"])
            data = stream.read(chunk["storedSize"])
        if len(data) != chunk["storedSize"]:
            raise ValueError("chunk payload is truncated")
        return data

    def read_raw(self, chunk: dict[str, Any]) -> bytes:
        data = self.read_stored(chunk)
        if chunk["codec"] == 0:
            raw = data
        elif chunk["codec"] == 1:
            raw = zlib.decompress(data)
        else:
            raise ValueError(f"unsupported chunk codec {chunk['codec']}")
        if len(raw) != chunk["rawSize"]:
            raise ValueError("chunk raw size does not match its TOC")
        if (zlib.crc32(raw) & 0xFFFFFFFF) != chunk["crc32"]:
            raise ValueError("chunk CRC does not match its TOC")
        return raw


class RetailImages:
    """Read supported, pointer-free image payloads from a retail IWD set.

    The package repair pass deliberately keeps the retail install outside the
    repository.  This index only retains IWD central-directory locations; an
    image is decoded when a selected map actually requests it.  That keeps a
    twenty-map repair from retaining the entire several-hundred-megabyte
    retail image pool in Python memory.
    """

    def __init__(self, root: Path):
        self.root = root.resolve()
        self.archives = sorted((self.root / "main").glob("*.iwd"),
                               key=lambda path: path.name.lower())
        self.locations: dict[str, list[tuple[Path, str]]] = {}
        self.source_cache: dict[str, tuple[Path, str] | None] = {}
        self.status_cache: dict[str, str] = {}
        for archive in self.archives:
            try:
                with zipfile.ZipFile(archive) as bundle:
                    for info in sorted(bundle.infolist(),
                                       key=lambda item: item.filename.lower()):
                        filename = info.filename.replace("\\", "/")
                        lowered = filename.lower()
                        if (not lowered.startswith("images/")
                                or not lowered.endswith(".iwi")):
                            continue
                        stem = Path(filename).stem.lower()
                        location = (archive, info.filename)
                        for key in (stem, _base(stem)):
                            entries = self.locations.setdefault(key, [])
                            if location not in entries:
                                entries.append(location)
            except (OSError, zipfile.BadZipFile):
                continue

    @staticmethod
    def _decode(archive: Path, filename: str) -> tuple[ImageRecord | None, str]:
        try:
            with zipfile.ZipFile(archive) as bundle:
                raw = bundle.read(filename)
            if len(raw) < 28:
                return None, "invalid"
            (tag, version, image_format, flags, width, height, depth,
             declared, _size0, _size1, _size2) = struct.unpack_from(
                 "<3sBBB3h4i", raw)
            if tag != b"IWi" or version != 6:
                return None, "invalid"
            if image_format not in (1, 2, 3, 5, 11, 12, 13):
                return None, "unsupported"
            if (width <= 0 or width > 4096 or height <= 0 or height > 4096
                    or depth != 1 or declared < 28 or declared > len(raw)):
                return None, "invalid"
            payload = raw[28:declared]
            if not payload or len(payload) > 8 * 1024 * 1024:
                return None, "invalid"
            fourcc = {1: 21, 2:21, 3:21, 5:21, 11: 0x31545844, 12: 0x33545844,
                      13: 0x35545844}[image_format]
            levels = (1 if flags & 2
                      else max(width.bit_length(), height.bit_length()))
            from shipment_typed_export import _reorder_iwi_mips as reorder, _expand_iwi_bitmap
            payload = reorder(payload, width, height, levels, image_format, flags)
            payload = _expand_iwi_bitmap(payload,image_format)
            return (len(payload), width, height, depth, levels, fourcc, flags,
                    payload), "found"
        except (OSError, KeyError, ValueError, struct.error, zipfile.BadZipFile):
            return None, "invalid"

    def lookup(self, name: str) -> tuple[ImageRecord | None, str]:
        key = name.lower()
        cached_source = self.source_cache.get(key, ...)
        if cached_source is not ...:
            if cached_source is None:
                return None, self.status_cache.get(key, "missing")
            record, status = self._decode(*cached_source)
            if record is not None:
                return record, status
            self.source_cache[key] = None
            self.status_cache[key] = status
            return None, status

        locations: list[tuple[Path, str]] = []
        seen: set[tuple[Path, str]] = set()
        for candidate in (key, _base(key)):
            for location in self.locations.get(candidate, []):
                if location not in seen:
                    locations.append(location)
                    seen.add(location)
        if not locations:
            self.source_cache[key] = None
            self.status_cache[key] = "missing"
            return None, "missing"
        last_status = "invalid"
        for location in locations:
            record, status = self._decode(*location)
            if record is not None:
                self.source_cache[key] = location
                self.status_cache[key] = "found"
                return record, "found"
            last_status = status
        self.source_cache[key] = None
        self.status_cache[key] = last_status
        return None, last_status


def _image_records(data: bytes) -> dict[str, tuple[int, int, int, int, int, int, int, bytes]]:
    if len(data) < 20:
        raise ValueError("VITI header is truncated")
    magic, version, count, declared = struct.unpack_from("<3IQ", data)
    if magic != 0x49544956 or version != 1 or count > 4096:
        raise ValueError("invalid VITI header")
    offset = 20
    aggregate = 0
    result: dict[str, tuple[int, int, int, int, int, int, int, bytes]] = {}
    for _ in range(count):
        if offset + 32 > len(data):
            raise ValueError("VITI record header is truncated")
        (name_bytes, payload_bytes, width, height, depth, levels, fmt,
         flags) = struct.unpack_from("<8I", data, offset)
        offset += 32
        if (name_bytes == 0 or payload_bytes == 0 or width == 0
                or height == 0 or depth != 1 or levels == 0
                or offset + name_bytes + payload_bytes > len(data)):
            raise ValueError("invalid VITI record")
        name = data[offset:offset + name_bytes].decode("utf-8")
        offset += name_bytes
        payload = bytes(data[offset:offset + payload_bytes])
        offset += payload_bytes
        aggregate += payload_bytes
        if name in result:
            raise ValueError(f"duplicate VITI image name: {name}")
        result[name] = (payload_bytes, width, height, depth, levels, fmt,
                        flags, payload)
    if offset != len(data) or aggregate != declared:
        raise ValueError("VITI size declaration is invalid")
    return result


def _write_image_records(records: Iterable[tuple[str, tuple[int, int, int, int, int, int, int, bytes]]]) -> bytes:
    ordered = sorted(records, key=lambda item: item[0])
    if len(ordered) > MAX_RECORDS:
        raise ValueError(
            f"effect image closure exceeds the record envelope "
            f"({len(ordered)}/{MAX_RECORDS})")
    payload_bytes = sum(len(item[1][7]) for item in ordered)
    if payload_bytes > MAX_DATA_BYTES:
        raise ValueError(
            f"effect image closure exceeds the data envelope "
            f"({payload_bytes}/{MAX_DATA_BYTES})")
    output = bytearray(struct.pack("<3IQ", 0x49544956, 1,
                                   len(ordered), payload_bytes))
    for name, record in ordered:
        _payload_bytes, width, height, depth, levels, fmt, flags, payload = record
        encoded = name.encode("utf-8")
        output.extend(struct.pack("<8I", len(encoded), len(payload), width,
                                  height, depth, levels, fmt, flags))
        output.extend(encoded)
        output.extend(payload)
    return bytes(output)


def _merge_exact_effect_images(
        source_data: bytes,
        shared_records: dict[str, ImageRecord]
        ) -> tuple[bytes, int, list[str]]:
    """Add exact shared FX records that are absent from one map's VITI.

    Effect materials such as smoke, debris, and crater decals are global COD4
    assets even when only one map's export happened to retain them. Reuse the
    byte-identical record already present in another effect-image chunk, while
    preserving every record from the selected map's sidecar on name
    collisions. The caller reports the merge so closure audits can distinguish
    reused source data from a newly extracted retail image.
    """
    records = _image_records(source_data)
    added: list[str] = []
    for name, record in sorted(shared_records.items()):
        if name in records:
            continue
        records[name] = record
        added.append(name)
    if not added:
        return source_data, 0, []
    return _write_image_records(records.items()), len(added), added


def _material_records(data: bytes) -> dict[str, dict[str, str]]:
    if len(data) < 20:
        raise ValueError("VITL header is truncated")
    magic, version, count, declared = struct.unpack_from("<3IQ", data)
    if magic != 0x4C544956 or version not in (1, 2, 3, 4, 5):
        raise ValueError("invalid VITL header")
    header_bytes = {1: 8, 2: 32, 3: 33, 4: 42, 5: 52}[version]
    offset = 20
    aggregate = 0
    result: dict[str, dict[str, str]] = {}
    for _ in range(count):
        if offset + header_bytes > len(data):
            raise ValueError("VITL record header is truncated")
        if version == 1:
            lengths = list(struct.unpack_from("<2I", data, offset)) + [0, 0, 0]
        else:
            lengths = list(struct.unpack_from("<5I", data, offset))
        offset += header_bytes
        values: list[str] = []
        for length in lengths:
            if offset + length > len(data):
                raise ValueError("VITL string is truncated")
            values.append(data[offset:offset + length].decode("utf-8"))
            offset += length
            aggregate += length
        result[values[0]] = {
            "color": values[1],
            "normal": values[2],
            "specular": values[3],
        }
    if offset != len(data) or aggregate != declared:
        raise ValueError("VITL size declaration is invalid")
    return result


def _model_records(data: bytes) -> dict[str, list[str]]:
    if len(data) < 20:
        raise ValueError("VITX header is truncated")
    magic, version, count, declared = struct.unpack_from("<3IQ", data)
    if magic != 0x58544956 or version not in (1, 2, 3, 4, 5):
        raise ValueError("invalid VITX header")
    offset = 20
    result: dict[str, list[str]] = {}
    for _ in range(count):
        if offset + 40 > len(data):
            raise ValueError("VITX model header is truncated")
        name_bytes, surface_count, vertex_count, index_count = struct.unpack_from(
            "<4I", data, offset)
        if offset + 40 + name_bytes > len(data):
            raise ValueError("VITX model name is truncated")
        name = data[offset + 40:offset + 40 + name_bytes].decode("utf-8")
        offset += 40 + name_bytes
        if version >= 2:
            if offset + 16 > len(data):
                raise ValueError("VITX skin header is truncated")
            bone_count, _roots, parent_bytes, _reserved = struct.unpack_from(
                "<4I", data, offset)
            skin_header_bytes = 24 if version == 5 else (20 if version == 4 else 16)
            if offset + skin_header_bytes > len(data):
                raise ValueError("VITX skin header is truncated")
            bone_name_bytes = (struct.unpack_from("<I", data, offset + 20)[0]
                               if version == 5 else 0)
            if version == 5 and bone_name_bytes != bone_count * 64:
                raise ValueError("VITX bone-name table is invalid")
            offset += skin_header_bytes
            offset += (parent_bytes + bone_name_bytes
                       + bone_count * (64 if version >= 3 else 32))
        materials: list[str] = []
        for _ in range(surface_count):
            if offset + 24 > len(data):
                raise ValueError("VITX surface header is truncated")
            material_bytes = struct.unpack_from("<I", data, offset)[0]
            offset += 24
            if offset + material_bytes > len(data):
                raise ValueError("VITX material name is truncated")
            if material_bytes:
                materials.append(data[offset:offset + material_bytes].decode("utf-8"))
            offset += material_bytes
        offset += vertex_count * 32
        if version >= 2:
            offset += vertex_count * 16
        offset += index_count * 2
        if offset > len(data):
            raise ValueError("VITX geometry is truncated")
        result[name] = materials
    if offset != len(data) or declared != len(data) - 20:
        raise ValueError("VITX size declaration is invalid")
    return result


def _entity_models(data: bytes) -> list[str]:
    if len(data) < 12:
        return []
    magic, version, text_bytes = struct.unpack_from("<3I", data)
    if magic != 0x45544956 or version != 1 or 12 + text_bytes != len(data):
        return []
    text = data[12:].decode("utf-8", "ignore")
    names: list[str] = []
    for block in re.findall(r"\{([^{}]*)\}", text, re.S):
        values = dict(re.findall(r'"([^\"]+)"\s+"([^\"]*)"', block))
        if (values.get("classname") in ("script_model", "vita_static_model")
                and values.get("model") and not values["model"].startswith("*")):
            names.append(values["model"])
    return list(dict.fromkeys(names))


def _world_materials(data: bytes) -> list[str]:
    if len(data) < 44:
        return []
    magic, version, vertex_count, index_count, surface_count = struct.unpack_from(
        "<5I", data)
    if magic != 0x57544956 or version not in (1, 2, 3):
        return []
    header_bytes = 44 if version == 1 else 120
    surface_bytes = 92 if version == 3 else 88
    surface_offset = header_bytes + vertex_count * 40 + index_count * 2
    if surface_offset + surface_count * surface_bytes != len(data):
        return []
    names: list[str] = []
    for index in range(surface_count):
        start = surface_offset + index * surface_bytes + 24
        name = data[start:start + 64].split(b"\0", 1)[0].decode("utf-8", "ignore")
        if name:
            names.append(name)
    return list(dict.fromkeys(names))


def _find_chunk(package: Package, kind: int, asset_id: int) -> dict[str, Any]:
    for chunk in package.chunks:
        if chunk["type"] == kind and chunk["assetId"] == asset_id:
            return chunk
    raise ValueError(f"missing chunk {kind}:{asset_id:016x}")


def _closure_slots(package: Package, index: int,
                   model_data: bytes | None = None) -> tuple[
        list[str], list[str], list[str], list[str], list[str], list[str]]:
    material = _material_records(package.read_raw(
        _find_chunk(package, MATERIAL_TYPE, 0x4D4C000000000000 | index)))
    models = (_model_records(model_data) if model_data is not None else
              _model_records(package.read_raw(
                  _find_chunk(package, MODEL_TYPE,
                              0x4D58000000000000 | index))))
    entities = _entity_models(package.read_raw(
        _find_chunk(package, WORLD_TYPE, 0x4D45000000000000 | index)))
    referenced: list[str] = []
    for requested in entities:
        model_name = requested if requested in models else next(
            (name for name in models if requested in name), None)
        if model_name:
            referenced.append(model_name)
    referenced = list(dict.fromkeys(referenced))
    model_names: list[str] = []
    model_normals: list[str] = []
    model_speculars: list[str] = []
    for model_name in referenced:
        for material_name in models[model_name]:
            record = material.get(material_name)
            if not record:
                continue
            if record["color"]:
                model_names.append(record["color"])
            if (record["normal"]
                    and record["normal"] != "$identitynormalmap"):
                model_normals.append(record["normal"])
            if record["specular"]:
                model_speculars.append(record["specular"])
    world_material_names = _world_materials(package.read_raw(
        _find_chunk(package, WORLD_TYPE, 0x4D50000000000000 | index)))
    world_names: list[str] = []
    world_normals: list[str] = []
    world_speculars: list[str] = []
    for name in world_material_names:
        record = material.get(name)
        if not record:
            continue
        if record["color"]:
            world_names.append(record["color"])
        if (record["normal"]
                and record["normal"] != "$identitynormalmap"):
            world_normals.append(record["normal"])
        if record["specular"]:
            world_speculars.append(record["specular"])

    def unique(values: Iterable[str]) -> list[str]:
        return list(dict.fromkeys(values))
    return (unique(model_names), unique(world_names), unique(model_normals),
            unique(world_normals), unique(model_speculars),
            unique(world_speculars))


def _closure_names(package: Package, index: int,
                   image_names: set[str], model_data: bytes | None = None
                   ) -> tuple[list[str], list[str]]:
    del image_names
    slots = _closure_slots(package, index, model_data)
    return slots[0], slots[1]


