from typing import Any, Iterable


HEADER = struct.Struct("<4sHHBBHQIQ32s")
TOC = struct.Struct("<IIQQQQIII12s")
MAGIC = b"KVAP"
HEADER_SIZE = 64
TOC_SIZE = 64
ALIGNMENT = 16
IMAGE_TYPE = 6
MODEL_TYPE = 7
MATERIAL_TYPE = 5
WORLD_TYPE = 4
EFFECTS_TYPE = 18
BASE_IMAGE_FAMILY = 0x4D49000000000000
EFFECTS_FAMILY = 0x4D46000000000000
EFFECT_IMAGES_FAMILY = 0x4D49070000000000
MODEL_COLOR_IMAGE_FAMILY = 0x4D49060000000000
# Keep the startup image stream within the known-stable VitaImageBundle
# envelope. Larger source-semantic closures are streamed as companion chunks;
# putting them into startup reproduces a Vita3K heap/UDF while loading the
# image bundle.
MAX_RECORDS = 512
MAX_DATA_BYTES = 64 * 1024 * 1024
# The common first-person color maps are emitted into a separate companion.
# Large-map world closures need a small amount of additional room for the
# authored wallpaper aliases while remaining well below the failed 70-72 MiB
# guest-heap experiments.
COLOR_CLOSURE_MAX_DATA_BYTES = MAX_DATA_BYTES + 512 * 1024

