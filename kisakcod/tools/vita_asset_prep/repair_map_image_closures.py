#!/usr/bin/env python3
"""Repair per-map render closures from an existing multi-map KVAP package.

The normal exporter performs this same closure from the retail IWD files.  A
previous package may still contain the authored image payload in another map's
VITI chunk, though, so this utility can repair a package after the read-only
retail source has been removed.  It never generates artwork: it only reuses
the exact payload and metadata already present in the package, then gives the
selected map an alias when two material records share the same IWI basename.
When requested, it can also replace each map's VITX model chunk from a fresh
set of Windows reference sidecars so large-map foliage and static dressing
stay synchronized with the image repair.
It can additionally refresh existing VFXA and effect-image chunks from the
source-derived conversion directory without changing any other package data.
When requested, exact effect-image records already present in another map's
VITI chunk are also reusable as a shared global-FX closure; no artwork is
generated by that merge.
"""

