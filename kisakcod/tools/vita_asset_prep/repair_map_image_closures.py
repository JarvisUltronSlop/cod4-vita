def _record_for(name: str, union: dict[str, tuple[int, int, int, int, int, int, int, bytes]],
                by_base: dict[str, tuple[str, tuple[int, int, int, int, int, int, int, bytes]]]
                ) -> tuple[str, tuple[int, int, int, int, int, int, int, bytes]] | None:
    if name in union:
        return name, union[name]
    fallback = by_base.get(_base(name))
    if not fallback:
        return None
    source_name, record = fallback
    # A #N suffix is a material alias, not a different pixel format. Rebind
    # the same authored payload under the exact material lookup key.
    return name, record


def _build_repaired_images(package: Package, index: int,
                           union: dict[str, ImageRecord],
                           by_base: dict[str, tuple[str, ImageRecord]],
                           per_map: list[dict[str, ImageRecord]],
                           map_lightmap_overrides: dict[str, ImageRecord] | None = None,
                           retail: RetailImages | None = None,
                           map_name: str = "",
                           model_data: bytes | None = None,
                           minimal_closure: bool = False,
                           color_closure: bool = False
                           ) -> tuple[bytes, dict[str, Any]]:
    (model_names, world_names, model_normals, world_normals,
     model_speculars, world_speculars) = _closure_slots(
         package, index, model_data)
    current = per_map[index]
    lightmaps = sorted(
        (name for name in current if name.lower().startswith("*lightmap")),
        key=lambda name: (0 if "_primary" in name.lower() else 1, name),
    )
    cubemaps = [name for name, record in current.items() if record[6] & 0x4]
    frontend = [name for name in current
                if name.lower().startswith("loadscreen_mp_")
                or name.lower().startswith("compass_map_mp_")]
    map_frontend = ([f"loadscreen_mp_{map_name}",
                     f"compass_map_mp_{map_name}"] if map_name else [])
    # Farm/Downpour and Cargo Ship/Wet Work load their rain materials from the
    # authored weather FX closure.  These are ordinary IWI image records, not
    # VENV metadata, so keep both exact retail aliases ahead of the long-tail
    # material list or the color-closure budget can evict them before the
    # runtime's weather pass gets a chance to bind the source texture.
    weather_priority_names = (
        ["rain_spray", "wind_rain_atlas"]
        if map_name in ("farm", "cargoship") else []
    )
    normal_names = list(dict.fromkeys(world_normals + model_normals))
    specular_names = list(dict.fromkeys(world_speculars + model_speculars))
    retail_preferred = set(
        model_names + world_names + normal_names + specular_names
        + list(CRITICAL_VIEWMODEL) + list(CRITICAL_FRONTEND)
        + list(CRITICAL_WORLD) + list(CRITICAL_MAP_WORLD)
        + list(CRITICAL_STATIC_MODEL)
        + map_frontend + frontend + weather_priority_names
    )
    priority: list[str] = []
    if color_closure:
        # This is an explicit source-color closure, not a map tint shortcut.
        # World/model colors are the hard requirement and must be selected
        # before optional presentation records.  The wider envelope is safe
        # here because large-map scalar startup immediately filters this
        # stream into the presentation and world/model phases.
        priority.extend(model_names)
        priority.extend(world_names)
        # Keep both authored lightmap atlases ahead of optional HUD aliases;
        # dropping a secondary atlas would silently flatten covered surfaces
        # even though the color closure itself still passed validation.
        priority.extend(lightmaps)
        priority.extend(cubemaps)
        priority.extend(map_frontend)
        priority.extend(frontend)
        priority.extend(weather_priority_names)
        # The menu font and low-health overlay are required for the retail
        # route.  Keep the overlay in the map-local closure: it is an exact
        # authored HUD image, not a safe candidate for a generated fallback.
        # The remaining diagnostic overlay/font tail can still yield to the
        # world/lightmap closure at the tightest enabled-map cutoff.
        # Reserve the frontend records that make the map-loading/menu route
        # usable before admitting the lower-value HUD/effect tail. This keeps
        # a retail-root repair from trading the authored font for a long-tail
        # alias when the largest map is close to the 64 MiB envelope.
        frontend_anchors = (
            "background_generic_blurred", "menu_screenbg", "menu_button",
            "menu_button_selected", "gamefonts_pc",
        )
        priority.extend(frontend_anchors)
        priority.extend(CRITICAL_MAP_WORLD)
        priority.extend(name for name in CRITICAL_FRONTEND
                        if name not in frontend_anchors
                        and name not in ("devfonts",))
    else:
        priority.extend(CRITICAL_VIEWMODEL)
        priority.extend(CRITICAL_FRONTEND)
        priority.extend(map_frontend)
        priority.extend(frontend)
        priority.extend(weather_priority_names)
        priority.extend(cubemaps)
        priority.extend(lightmaps)
        # Exact color maps are the map's primary visual closure. Speculars
        # follow them before the optional normal tail because the source lit
        # pass samples the authored mask on every lit surface and must not
        # silently lose it at the bounded envelope cutoff.
        priority.extend(model_names)
        priority.extend(world_names)
    if not minimal_closure and not color_closure:
        priority.extend(CRITICAL_WORLD)
        priority.extend(CRITICAL_STATIC_MODEL)
        # Keep the map's already-authored semantic tail when there is room.
        # This preserves any generated light/UI records not represented in
        # VITL while keeping the selected map's retail world/model closure
        # first.
        priority.extend(current)
        priority.extend(specular_names)
        # Add exact retail normal layers after the source specular closure. This
        # protects visible props and authored HUD records from being displaced
        # by a large normal-map long tail under the fixed per-map envelope.
        priority.extend(normal_names)
    elif minimal_closure and not color_closure:
        # The exact world/model color closure already covers every material
        # referenced by the selected map.  The older safety-anchor lists are
        # redundant once that closure is computed from the fresh VITL/VITX
        # sidecars, and keeping them ahead of normals wastes the last few MiB
        # on aliases that are not used by this map. Preserve as many authored
        # normal layers as the envelope allows; the scalar path uses them for
        # source lighting and the VitaGL path binds them directly.
        priority.extend(specular_names)
        priority.extend(normal_names)
    selected: dict[str, ImageRecord] = {}
    missing: list[str] = []
    skipped: list[str] = []
    available: set[str] = set()
    retail_attempted: dict[str, str] = {}
    retail_selected: set[str] = set()
    retail_bytes = 0
    total = 0

    def choose(requested: str) -> tuple[str, ImageRecord, str] | None:
        if retail is not None and requested in retail_preferred:
            retail_record, status = retail.lookup(requested)
            retail_attempted.setdefault(requested, status)
            # A current authored cubemap must remain a cubemap.  If a retail
            # archive only contains a 2D basename variant, retain the current
            # cube payload instead of silently flattening the sky.
            if (retail_record is not None
                    and (requested not in current
                         or not current[requested][7])
                    and (requested not in cubemaps or retail_record[6] & 0x4)):
                return requested, retail_record, "retail"
        # The bounded source package may carry a high-resolution atlas that
        # leaves no room for the selected map's complete retail image closure.
        # A union package can provide the same authored lightmap at the
        # exporter-selected Vita resolution; keep this override explicit and
        # map-local rather than accidentally selecting another map's atlas.
        if (map_lightmap_overrides is not None
                and requested in map_lightmap_overrides):
            return requested, map_lightmap_overrides[requested], "union-map"
        # Names such as *lightmap0_primary are intentionally reused by every
        # map.  The global union is only a source for missing closure records;
        # an exact record already present in the selected map must win or a
        # repaired Crossfire package can accidentally bind Shipment's atlas.
        if requested in current:
            return requested, current[requested], "map"
        found = _record_for(requested, union, by_base)
        if found is None:
            return None
        name, record = found
        return name, record, "package"

    for requested in dict.fromkeys(priority):
        found = choose(requested)
        if found is None:
            if (requested in model_names or requested in world_names
                    or requested in frontend or requested in map_frontend):
                missing.append(requested)
            continue
        name, record, source = found
        available.add(requested)
        if name in selected:
            continue
        size = len(record[7])
        data_limit = (COLOR_CLOSURE_MAX_DATA_BYTES
                      if color_closure else MAX_DATA_BYTES)
        if len(selected) >= MAX_RECORDS or total + size > data_limit:
            skipped.append(requested)
            continue
        selected[name] = record
        total += size
        if source == "retail":
            retail_selected.add(requested)
            retail_bytes += size
    required = list(dict.fromkeys(model_names + world_names + frontend
                                  + map_frontend + weather_priority_names
                                  + list(CRITICAL_HUD_REQUIRED)))
    not_selected = [name for name in required
                    if name in available and name not in selected]
    if not_selected:
        raise ValueError(
            f"map {index}: required image closure exceeded the envelope "
                f"(selected={len(selected)}/{MAX_RECORDS} bytes={total}/"
                f"{COLOR_CLOSURE_MAX_DATA_BYTES if color_closure else MAX_DATA_BYTES}): "
                + ", ".join(not_selected[:12]))
    unavailable = [name for name in required if name not in available]
    if unavailable:
        missing.extend(unavailable)
    output = _write_image_records(selected.items())
    retail_missing = [name for name, status in retail_attempted.items()
                      if status == "missing"]
    retail_unsupported = [name for name, status in retail_attempted.items()
                          if status == "unsupported"]
    retail_invalid = [name for name, status in retail_attempted.items()
                      if status == "invalid"]
    return output, {
        "mapIndex": index,
        "mapName": map_name,
        "minimalClosure": minimal_closure,
        "colorClosure": color_closure,
        "dataLimitBytes": (COLOR_CLOSURE_MAX_DATA_BYTES
                            if color_closure else MAX_DATA_BYTES),
        "records": len(selected),
        "dataBytes": total,
        "modelColorNames": len(model_names),
        "worldColorNames": len(world_names),
        "modelColorsPresent": sum(name in selected for name in model_names),
        "worldColorsPresent": sum(name in selected for name in world_names),
        "normalNames": len(normal_names),
        "normalPayloads": sum(name in selected for name in normal_names),
        "specularNames": len(specular_names),
        "specularPayloads": sum(name in selected for name in specular_names),
        "retailRecords": len(retail_selected),
        "retailDataBytes": retail_bytes,
        "retailModelColorsPresent": sum(
            name in retail_selected for name in model_names),
        "retailWorldColorsPresent": sum(
            name in retail_selected for name in world_names),
        "retailMissingNames": retail_missing,
        "retailUnsupportedNames": retail_unsupported,
        "retailInvalidNames": retail_invalid,
        "missingSourceNames": list(dict.fromkeys(missing)),
        "skippedNames": list(dict.fromkeys(skipped)),
    }


def _sha256_raw(package: Package, chunk: dict[str, Any]) -> bytes:
    if chunk.get("replacement") is not None:
        return hashlib.sha256(chunk["replacement"]).digest()
    if chunk["codec"] == 0:
        digest = hashlib.sha256()
        with package.path.open("rb") as stream:
            stream.seek(chunk["offset"])
            remaining = chunk["storedSize"]
            while remaining:
                block = stream.read(min(4 * 1024 * 1024, remaining))
                if not block:
                    raise ValueError("chunk is truncated while hashing")
                digest.update(block)
                remaining -= len(block)
        return digest.digest()
    return hashlib.sha256(package.read_raw(chunk)).digest()


def repair(package_path: Path, output_path: Path,
           retail_root: Path | None = None,
           model_source_root: Path | None = None,
           map_image_root: Path | None = None,
           disabled_map_indices: set[int] | None = None,
           minimal_closure: bool = False,
           union_package_paths: Iterable[Path] | None = None,
           color_closure: bool = False,
           effect_root: Path | None = None,
           effects_only: bool = False,
           merge_effect_images: bool = False) -> dict[str, Any]:
    package = Package(package_path)
    retail = RetailImages(retail_root) if retail_root is not None else None
    disabled_map_indices = set(disabled_map_indices or ())
    union_packages: list[Package] = []
    for union_path in union_package_paths or ():
        resolved_union_path = union_path.resolve()
        if resolved_union_path == package_path.resolve():
            continue
        union_packages.append(Package(resolved_union_path))
    shared_effect_images: dict[str, ImageRecord] = {}
    if merge_effect_images:
        # Keep the first exact record for a name. The package writer's
        # deterministic map ordering makes this stable, and later maps cannot
        # replace a source-identical global FX payload accidentally.
        for chunk in package.chunks:
            if (chunk["type"] != IMAGE_TYPE
                    or (chunk["assetId"] & 0xFFFFFFFFFFFFFF00)
                    != EFFECT_IMAGES_FAMILY):
                continue
            for name, record in _image_records(package.read_raw(chunk)).items():
                shared_effect_images.setdefault(name, record)
        for union_package in union_packages:
            for chunk in union_package.chunks:
                if (chunk["type"] != IMAGE_TYPE
                        or (chunk["assetId"] & 0xFFFFFFFFFFFFFF00)
                        != EFFECT_IMAGES_FAMILY):
                    continue
                for name, record in _image_records(
                        union_package.read_raw(chunk)).items():
                    shared_effect_images.setdefault(name, record)
    # The current package has several image families: ordinary map colours,
    # reflection probes, and streamed normal/specular companions.  Only the
    # ordinary map-colour family is repaired here; treating every image chunk
    # as one of the twenty maps misaligns indices as soon as deferred maps or
    # semantic segments are present.
    image_chunks = [] if effects_only else [
        chunk for chunk in package.chunks
        if chunk["type"] == IMAGE_TYPE
        and (chunk["assetId"] & 0xFFFFFFFFFFFFFF00) == BASE_IMAGE_FAMILY
    ]
    if not effects_only and len(image_chunks) < 2:
        raise ValueError("package does not contain a multi-map image closure")
    union: dict[str, tuple[int, int, int, int, int, int, int, bytes]] = {}
    by_base: dict[str, tuple[str, tuple[int, int, int, int, int, int, int, bytes]]] = {}
    per_map: list[dict[str, Any]] = [{} for _ in MAP_NAMES]
    for chunk in image_chunks:
        map_index = chunk["assetId"] & 0xFF
        if map_index >= len(MAP_NAMES) or per_map[map_index]:
            raise ValueError(
                f"invalid or duplicate base image map index: {map_index}")
        records = _image_records(package.read_raw(chunk))
        per_map[map_index] = records
        for name, record in records.items():
            union.setdefault(name, record)
            by_base.setdefault(_base(name), (name, record))
    for name, record in BUILTIN_IMAGE_RECORDS.items():
        union.setdefault(name, record)
        by_base.setdefault(_base(name), (name, record))
    if not effects_only and any(
            not per_map[index] for index in range(len(MAP_NAMES))
            if index not in disabled_map_indices):
        missing = [str(index) for index, records in enumerate(per_map)
                   if not records and index not in disabled_map_indices]
        raise ValueError("missing enabled base image map chunks: "
                         + ", ".join(missing))
    # A regenerated map-side VITI stream is a valid source closure in its own
    # right.  Prefer its exact records for that map while retaining the old
    # package union as a compatibility source for aliases it does not contain.
    # This is important after a renderer-side closure repair: the package may
    # still have the same assets.csv hash while its older image chunk predates
    # newly recovered retail world images.
    map_image_sources: dict[int, Path] = {}
    map_image_data: dict[int, bytes] = {}
    if map_image_root is not None:
        map_image_root = map_image_root.resolve()
        for index, map_name in enumerate(MAP_NAMES):
            source_path = (map_image_root / f"{index:02d}-{map_name}"
                           / "vita_images.bin")
            if not source_path.is_file():
                raise FileNotFoundError(
                    f"missing map image sidecar for {map_name}: {source_path}")
            # Parse now so a malformed source cannot produce a partially
            # rewritten package later in the repair pass.
            source_data = source_path.read_bytes()
            _image_records(source_data)
            map_image_sources[index] = source_path
            map_image_data[index] = source_data
        for index, source_path in map_image_sources.items():
            source_records = _image_records(map_image_data[index])
            per_map[index] = source_records
            for name, record in source_records.items():
                union.setdefault(name, record)
                by_base.setdefault(_base(name), (name, record))
    # The common first-person color companion is intentionally kept outside
    # the per-map base-image family.  Include its existing records in the
    # lookup union before validating a layered repair; otherwise a retail-root
    # pass can falsely report every M4/hands alias missing even though the
    # package already carries the validated companion chunk.
    existing_model_color_chunk = next(
        (chunk for chunk in package.chunks
         if chunk["type"] == IMAGE_TYPE
         and chunk["assetId"] == MODEL_COLOR_IMAGE_FAMILY),
        None,
    )
    if existing_model_color_chunk is not None:
        for name, record in _image_records(
                package.read_raw(existing_model_color_chunk)).items():
            union.setdefault(name, record)
            by_base.setdefault(_base(name), (name, record))
    # A repair source may be a previously exported retail-image package while
    # the target carries newer renderer/environment chunks.  Merge only the
    # exact image records into the target union; the target's map-local record
    # wins on name collisions, so this cannot overwrite newer dimensions or
    # payloads.  This makes the closure repair reproducible after the retail
    # IWD directory has been removed from the workstation.
    union_map_lightmaps: dict[int, dict[str, ImageRecord]] = {}
    for union_package in union_packages:
        union_image_chunks = [chunk for chunk in union_package.chunks
                              if chunk["type"] == IMAGE_TYPE]
        for chunk in union_image_chunks:
            union_index = chunk["assetId"] & 0xFFFFFFFF
            map_records = union_map_lightmaps.setdefault(union_index, {})
            for name, record in _image_records(
                    union_package.read_raw(chunk)).items():
                if name.lower().startswith("*lightmap"):
                    map_records[name] = record
                union.setdefault(name, record)
                by_base.setdefault(_base(name), (name, record))

    invalid_disabled = sorted(
        index for index in disabled_map_indices
        if index < 0 or index >= len(MAP_NAMES)
    )
    if invalid_disabled:
        raise ValueError("disabled map index out of range: "
                         + ", ".join(str(index) for index in invalid_disabled))

    model_source_data: dict[int, bytes] = {}
    if model_source_root is not None:
        model_source_root = model_source_root.resolve()
        for index, map_name in enumerate(MAP_NAMES):
            source_path = (model_source_root / f"{index:02d}-{map_name}"
                           / "vita_models.bin")
            if not source_path.is_file():
                raise FileNotFoundError(
                    f"missing model sidecar for {map_name}: {source_path}")
            model_data = source_path.read_bytes()
            _model_records(model_data)
            model_source_data[index] = model_data

    summaries: list[dict[str, Any]] = []
    image_chunks.sort(key=lambda chunk: chunk["assetId"] & 0xFF)
    for chunk in image_chunks:
        index = chunk["assetId"] & 0xFF
        if index in disabled_map_indices:
            summaries.append({
                "mapIndex": index,
                "mapName": MAP_NAMES[index],
                "disabled": True,
                "source": "base package closure preserved",
                "records": len(per_map[index]),
                "dataBytes": sum(len(record[7])
                                  for record in per_map[index].values()),
            })
            continue
        exact_source = map_image_data.get(index)
        if exact_source is not None and not minimal_closure and not color_closure:
            # The caller supplied a validated, already-budgeted per-map VITI
            # stream. Install it byte-for-byte so this operation cannot undo
            # that closure by re-ranking a long tail against the 64 MiB cap.
            records = per_map[index]
            chunk["replacement"] = exact_source
            chunk["codec"] = 0
            chunk["storedSize"] = len(exact_source)
            chunk["rawSize"] = len(exact_source)
            chunk["crc32"] = zlib.crc32(exact_source) & 0xFFFFFFFF
            summaries.append({
                "mapIndex": index,
                "mapName": MAP_NAMES[index],
                "source": str(map_image_sources[index]),
                "exactSource": True,
                "records": len(records),
                "dataBytes": sum(len(record[7])
                                  for record in records.values()),
            })
            continue
        replacement, summary = _build_repaired_images(
            package, index, union, by_base, per_map,
            union_map_lightmaps.get(index), retail, MAP_NAMES[index],
            model_source_data.get(index), minimal_closure, color_closure)
        chunk["replacement"] = replacement
        chunk["codec"] = 0
        chunk["storedSize"] = len(replacement)
        chunk["rawSize"] = len(replacement)
        chunk["crc32"] = zlib.crc32(replacement) & 0xFFFFFFFF
        summaries.append(summary)

    effect_summaries: list[dict[str, Any]] = []
    if effect_root is not None:
        effect_root = effect_root.resolve()
        effect_families = (
            (EFFECTS_TYPE, EFFECTS_FAMILY, "effects", True),
            (IMAGE_TYPE, EFFECT_IMAGES_FAMILY, "effect-images", False),
        )
        for chunk_type, family, folder, required in effect_families:
            candidates = [chunk for chunk in package.chunks
                          if chunk["type"] == chunk_type
                          and (chunk["assetId"] & 0xFFFFFFFFFFFFFF00) == family]
            for chunk in sorted(candidates,
                                key=lambda value: value["assetId"] & 0xFF):
                index = chunk["assetId"] & 0xFF
                if index >= len(MAP_NAMES):
                    raise ValueError(
                        f"invalid {folder} map index: {index}")
                try:
                    source = _map_auxiliary_source(
                        effect_root, folder, index, MAP_NAMES[index])
                except FileNotFoundError:
                    if required and not effects_only:
                        raise
                    merged_records = 0
                    merged_names: list[str] = []
                    if (folder == "effect-images" and merge_effect_images
                            and shared_effect_images):
                        replacement, merged_records, merged_names = (
                            _merge_exact_effect_images(
                                package.read_raw(chunk), shared_effect_images))
                        chunk["replacement"] = replacement
                        chunk["codec"] = 0
                        chunk["storedSize"] = len(replacement)
                        chunk["rawSize"] = len(replacement)
                        chunk["crc32"] = zlib.crc32(replacement) & 0xFFFFFFFF
                    effect_summaries.append({
                        "mapIndex": index,
                        "mapName": MAP_NAMES[index],
                        "family": folder,
                        "source": "package preserved",
                        "bytes": chunk["rawSize"],
                        "mergedSharedRecords": merged_records,
                        "mergedSharedNames": merged_names[:32],
                    })
                    continue
                replacement = source.read_bytes()
                if not replacement:
                    raise ValueError(f"empty {folder} sidecar: {source}")
                if required and replacement[:4] != b"VFXA":
                    raise ValueError(f"invalid VFXA sidecar: {source}")
                merged_records = 0
                merged_names: list[str] = []
                if (folder == "effect-images" and merge_effect_images
                        and shared_effect_images):
                    replacement, merged_records, merged_names = (
                        _merge_exact_effect_images(
                            replacement, shared_effect_images))
                chunk["replacement"] = replacement
                chunk["codec"] = 0
                chunk["storedSize"] = len(replacement)
                chunk["rawSize"] = len(replacement)
                chunk["crc32"] = zlib.crc32(replacement) & 0xFFFFFFFF
                effect_summaries.append({
                    "mapIndex": index,
                    "mapName": MAP_NAMES[index],
                    "family": folder,
                    "source": str(source),
                    "bytes": len(replacement),
                    "mergedSharedRecords": merged_records,
                    "mergedSharedNames": merged_names[:32],
                })

    model_summaries: list[dict[str, Any]] = []
    if model_source_root is not None:
        for index, map_name in enumerate(MAP_NAMES):
            source_path = (model_source_root / f"{index:02d}-{map_name}"
                           / "vita_models.bin")
            replacement = model_source_data[index]
            records = _model_records(replacement)
            model_chunk = next(
                (candidate for candidate in package.chunks
                 if candidate["type"] == MODEL_TYPE
                 and candidate["assetId"] == (0x4D58000000000000 | index)),
                None,
            )
            if model_chunk is None:
                raise ValueError(f"missing model chunk for {map_name}")
            if index in disabled_map_indices:
                model_summaries.append({
                    "mapIndex": index,
                    "mapName": map_name,
                    "source": "base package model preserved",
                    "disabled": True,
                    "records": len(_model_records(
                        package.read_raw(model_chunk))),
                    "bytes": model_chunk["rawSize"],
                })
                continue
            model_chunk["replacement"] = replacement
            model_chunk["codec"] = 0
            model_chunk["storedSize"] = len(replacement)
            model_chunk["rawSize"] = len(replacement)
            model_chunk["crc32"] = zlib.crc32(replacement) & 0xFFFFFFFF
            model_summaries.append({
                "mapIndex": index,
                "mapName": map_name,
                "source": str(source_path),
                "records": len(records),
                "bytes": len(replacement),
            })

    model_color_summary: dict[str, Any] | None = None
    if color_closure:
        # Keep the common first-person color maps out of the bounded per-map
        # world stream.  They are identical across MP maps and are appended
        # after the map image phase, matching the existing streamed normal /
        # specular companion contract.
        model_color_records: dict[str, ImageRecord] = {}
        model_color_missing: list[str] = []
        for requested in CRITICAL_VIEWMODEL:
            found = _record_for(requested, union, by_base)
            if found is None:
                model_color_missing.append(requested)
                continue
            name, record = found
            model_color_records[name] = record
        if model_color_missing:
            raise ValueError(
                "model color companion is missing authored records: "
                + ", ".join(model_color_missing))
        existing_model_color = next(
            (chunk for chunk in package.chunks
             if chunk["assetId"] == MODEL_COLOR_IMAGE_FAMILY),
            None,
        )
        if existing_model_color is not None:
            # A repair may be layered over a previously validated color
            # closure. Preserve its common first-person companion rather than
            # appending a duplicate chunk; this also keeps late frontend
            # records and the companion's residency contract stable while a
            # retail-root pass fills map-side aliases.
            model_color_data = package.read_raw(existing_model_color)
            model_color_records = _image_records(model_color_data)
            model_color_source = "existing validated companion preserved"
        else:
            model_color_data = _write_image_records(model_color_records.items())
            package.chunks.append({
                "index": len(package.chunks),
                "type": IMAGE_TYPE,
                "chunkFlags": 0,
                "assetId": MODEL_COLOR_IMAGE_FAMILY,
                "offset": 0,
                "storedSize": len(model_color_data),
                "rawSize": len(model_color_data),
                "alignment": ALIGNMENT,
                "codec": 0,
                "crc32": zlib.crc32(model_color_data) & 0xFFFFFFFF,
                "reserved": bytes(12),
                "replacement": model_color_data,
            })
            model_color_source = "all-map authored image union"
        model_color_summary = {
            "assetId": f"0x{MODEL_COLOR_IMAGE_FAMILY:016x}",
            "records": len(model_color_records),
            "dataBytes": sum(len(record[7])
                              for record in model_color_records.values()),
            "bytes": len(model_color_data),
            "source": model_color_source,
            "missingSourceNames": model_color_missing,
        }

    cursor = _align(HEADER_SIZE + TOC_SIZE * len(package.chunks))
    for chunk in package.chunks:
        chunk["newOffset"] = cursor
        cursor = _align(cursor + chunk["storedSize"])

    digest = hashlib.sha256()
    for chunk in sorted(package.chunks,
                        key=lambda value: (value["type"], value["assetId"], value["index"])):
        digest.update(struct.pack("<IQQI", chunk["type"], chunk["assetId"],
                                  chunk["rawSize"], chunk["codec"]))
        digest.update(_sha256_raw(package, chunk))
    package_id = int.from_bytes(digest.digest()[:8], "little")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with package_path.open("rb") as source, output_path.open("wb") as destination:
        header = HEADER.pack(MAGIC, package.major, package.minor, 1, package.flags,
                             HEADER_SIZE, HEADER_SIZE, len(package.chunks),
                             package_id, package.source_hash)
        destination.write(header)
        for chunk in package.chunks:
            destination.write(TOC.pack(
                chunk["type"], chunk["chunkFlags"], chunk["assetId"],
                chunk["newOffset"], chunk["storedSize"], chunk["rawSize"],
                chunk["alignment"], chunk["codec"], chunk["crc32"],
                chunk["reserved"]))
        destination.write(bytes(_align(destination.tell()) - destination.tell()))
        for chunk in package.chunks:
            destination.write(bytes(chunk["newOffset"] - destination.tell()))
            replacement = chunk.get("replacement")
            if replacement is not None:
                destination.write(replacement)
                continue
            source.seek(chunk["offset"])
            remaining = chunk["storedSize"]
            while remaining:
                block = source.read(min(4 * 1024 * 1024, remaining))
                if not block:
                    raise ValueError("chunk is truncated while copying")
                destination.write(block)
                remaining -= len(block)

    report = {
        "format": "KVAP",
        "version": f"{package.major}.{package.minor}",
        "packageId": f"0x{package_id:016x}",
        "sourceHash": package.source_hash.hex(),
        "output": str(output_path.resolve()),
        "retailRoot": str(retail.root) if retail is not None else None,
        "retailArchives": [str(path) for path in retail.archives] if retail else [],
        "modelSourceRoot": (str(model_source_root)
                            if model_source_root is not None else None),
        "mapImageRoot": (str(map_image_root)
                          if map_image_root is not None else None),
        "effectRoot": (str(effect_root)
                       if effect_root is not None else None),
        "imageUnionPackages": [str(path.resolve())
                               for path in union_package_paths or ()],
        "minimalClosure": minimal_closure,
        "colorClosure": color_closure,
        "mergeEffectImages": merge_effect_images,
        "disabledMapIndices": sorted(disabled_map_indices),
        "bytes": output_path.stat().st_size,
        "imageClosureRepair": summaries,
        "effectClosureRepair": effect_summaries,
        "modelClosureRepair": model_summaries,
        "modelColorCompanion": model_color_summary,
        "chunks": [{
            "type": chunk["type"],
            "assetId": f"0x{chunk['assetId']:016x}",
            "offset": chunk["newOffset"],
            "storedBytes": chunk["storedSize"],
            "rawBytes": chunk["rawSize"],
            "codec": chunk["codec"],
            "crc32": f"{chunk['crc32']:08x}",
        } for chunk in package.chunks],
    }
    output_path.with_suffix(output_path.suffix + ".report.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8")
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--retail-root", type=Path,
                        help="Optional read-only Call of Duty 4 install for exact IWI payloads")
    parser.add_argument("--model-source-root", type=Path,
                        help="Optional map sidecar root containing NN-map/vita_models.bin closures")
    parser.add_argument("--map-image-root", type=Path,
                        help="Optional map sidecar root containing NN-map/vita_images.bin closures")
    parser.add_argument("--effect-root", type=Path,
                        help="Optional conversion root containing effects/ and effect-images/ map sidecars")
    parser.add_argument("--effects-only", action="store_true",
                        help="Rewrite only authored effect chunks and preserve all image closures byte-for-byte")
    parser.add_argument("--merge-effect-images", action="store_true",
                        help="Reuse exact effect-image records already present in other map VITI chunks")
    parser.add_argument("--union-package", type=Path, action="append", default=[],
                        help="Optional prior KVAP whose exact image records may fill the repair union")
    parser.add_argument("--disabled-map", type=int, action="append", default=[],
                        help="Preserve the base closure/model and leave this map disabled")
    parser.add_argument("--minimal-closure", action="store_true",
                        help="Keep exact world/model color closure plus fitting normal maps")
    parser.add_argument("--color-closure", action="store_true",
                        help="Build the widened source-derived world/model color closure with frontend and viewmodel anchors")
    args = parser.parse_args()
    if args.package.resolve() == args.output.resolve():
        raise SystemExit("--output must be different from --package")
    report = repair(
        args.package.resolve(), args.output.resolve(),
        args.retail_root.resolve() if args.retail_root else None,
        args.model_source_root.resolve() if args.model_source_root else None,
        args.map_image_root.resolve() if args.map_image_root else None,
        set(args.disabled_map),
        args.minimal_closure,
        args.union_package,
        args.color_closure,
        args.effect_root.resolve() if args.effect_root else None,
        args.effects_only,
        args.merge_effect_images,
    )
    print(json.dumps({
        "output": report["output"],
        "bytes": report["bytes"],
        "packageId": report["packageId"],
        "maps": report["imageClosureRepair"],
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
