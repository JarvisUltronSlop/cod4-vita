"""Local diagnostic sidecars only. Never modifies the owned source streams."""
import hashlib
import json
from pathlib import Path
import subprocess

AMBIENT=('amb_middle_east1v7_lr.mp3','amb_middle_east1v7_lsrs.mp3')
def sha(path):
    with path.open('rb') as f: return hashlib.file_digest(f,'sha256').hexdigest()

def prepare(root, build=True):
    source=root/'Data/CODVIT001/stream/sound'
    output=root/'deploy/benchmark-round6'
    output.mkdir(parents=True,exist_ok=True)
    recipe=output/'audio-conversion.json'
    previous=json.loads(recipe.read_text()) if recipe.exists() else {}
    tool=root/'build/host-tests/Release/vita-benchmark-pcm-convert.exe'
    if build:
        subprocess.run(['cmake','--build',str(root/'build/host-tests'),'--config','Release',
                        '--target','vita-benchmark-pcm-convert'],check=True)
    converter_hash=sha(tool)
    identity={}; conversions={}
    # Include all source files eligible for the looped background-stream test.
    for group in ('ambient','amb_emitters','music'):
        for path in sorted((source/group).rglob('*')):
            if path.is_file():
                identity['ux0:data/CODVIT001/stream/sound/'+path.relative_to(source).as_posix()]=sha(path)
    for name in AMBIENT:
        original=source/'ambient'/name
        sidecar=output/'Data/CODVIT001/stream/sound/ambient'/(name+'.bench.wav')
        sidecar.parent.mkdir(parents=True,exist_ok=True)
        old=previous.get('files',{}).get(name,{})
        fresh=(old.get('sourceSha256')==sha(original) and previous.get('converterSha256')==converter_hash
               and sidecar.exists() and old.get('pcmSha256')==sha(sidecar))
        if fresh:
            entry=old
        else:
            if not build: raise ValueError('Audio sidecar requires regeneration: '+name)
            entry=json.loads(subprocess.check_output([str(tool),str(original),str(sidecar)],text=True))
            entry.update(sourceSha256=sha(original),pcmSha256=sha(sidecar),pcmBytes=sidecar.stat().st_size)
        conversions[name]=entry
        identity['ux0:data/CODVIT001/stream/sound/ambient/'+name+'.bench.wav']=entry['pcmSha256']
    data={'schema':1,'converterSha256':converter_hash,'files':conversions,'actualFiles':identity}
    recipe.write_text(json.dumps(data,indent=2)+'\n')
    header=root/'kisakcod/src/vita/vita_benchmark_audio_inputs.h'
    contents='#pragma once\n// Generated by prepare_benchmark_audio.py; source assets remain local.\nnamespace kisak::vita {\ninline constexpr const char* kAudioBenchmarkIdentityPaths[] = {\n'
    contents+=''.join('    '+json.dumps(path)+',\n' for path in sorted(identity))
    contents+='};\n}\n'
    if not header.exists() or header.read_text()!=contents:
        if not build: raise ValueError('Audio input header differs from the built candidate')
        header.write_text(contents)
    return data

if __name__=='__main__':
    print(json.dumps(prepare(Path(__file__).resolve().parents[3]),indent=2))
